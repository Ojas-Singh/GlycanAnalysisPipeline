def _levels_of(data: Dict[str, Any]) -> Dict[str, Dict[str, float]]:
    levels = ((data.get("archetype") or {}).get("cluster_levels") or {})
    return {key: dict(value.get("clusters") or {}) for key, value in levels.items() if isinstance(value, dict)}


def _representatives(table: Optional[Path]) -> Optional[Dict[str, int]]:
    """Cluster -> source frame of its representative, from ``torsion_level_<n>_reps.csv``."""
    import csv

    if table is None or not Path(table).is_file():
        return None
    out: Dict[str, int] = {}
    with open(table, newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            try:
                out[f"Cluster {int(float(row['cluster_id']))}"] = int(float(row.get("source_frame") or row["frame"]))
            except (KeyError, TypeError, ValueError):
                continue
    return out


def _total_variation(before: Dict[str, float], after: Dict[str, float]) -> Optional[float]:
    if not before or not after:
        return None
    keys = set(before) | set(after)
    return round(0.5 * sum(abs(float(before.get(k, 0.0)) - float(after.get(k, 0.0))) for k in keys) / 100.0, 4)


def diff_entry(old_data: Dict[str, Any], new_data: Dict[str, Any], old_files: Dict[str, Dict[str, Any]],
               new_files: Dict[str, Dict[str, Any]], old_reps: Optional[Dict[str, Optional[Path]]] = None,
               new_reps: Optional[Dict[str, Optional[Path]]] = None) -> Dict[str, Any]:
    """What an administrator sees before approving: names, simulation, search metadata, analysis, files."""
    def changed(before: Any, after: Any) -> Optional[Dict[str, Any]]:
        return None if before == after else {"before": before, "after": after}

    names: Dict[str, Any] = {}
    for variant in ("archetype", "alpha", "beta"):
        before, after = old_data.get(variant) or {}, new_data.get(variant) or {}
        for key in ("name", "glycam", "iupac", "iupac_extended", "glytoucan", "wurcs", "mass", "oxford", "components"):
            if variant != "archetype" and key in ("mass", "oxford", "components"):
                continue
            difference = changed(before.get(key), after.get(key))
            if difference:
                names[f"{variant}.{key}"] = difference
    archetype_before, archetype_after = old_data.get("archetype") or {}, new_data.get("archetype") or {}
    simulation = {key: difference for key in ("length", "package", "forcefield", "water", "temperature", "pressure", "salt")
                  if (difference := changed(archetype_before.get(key), archetype_after.get(key)))}
    search_before, search_after = old_data.get("search_meta") or {}, new_data.get("search_meta") or {}
    search: Dict[str, Any] = {}
    for key in ("keywords", "common_names", "aliases"):
        before, after = set(search_before.get(key) or []), set(search_after.get(key) or [])
        if before != after:
            search[key] = {"added": sorted(after - before), "removed": sorted(before - after)}
    for key in ("description", "curator_note"):
        difference = changed(search_before.get(key), search_after.get(key))
        if difference:
            search[key] = difference
    analysis: Dict[str, Any] = {"levels": {}}
    old_levels, new_levels = _levels_of(old_data), _levels_of(new_data)
    for level in sorted(set(old_levels) | set(new_levels)):
        before, after = old_levels.get(level) or {}, new_levels.get(level) or {}
        row: Dict[str, Any] = {"populations": {"before": before, "after": after},
                               "total_variation": _total_variation(before, after)}
        reps_before = _representatives((old_reps or {}).get(level))
        reps_after = _representatives((new_reps or {}).get(level))
        if reps_before is not None or reps_after is not None:
            row["representative_source_frames"] = {"before": reps_before, "after": reps_after,
                                                   "same": reps_before == reps_after}
        analysis["levels"][level] = row
    entropy = changed(archetype_before.get("entropy"), archetype_after.get("entropy"))
    if entropy:
        analysis["entropy"] = entropy
    added = sorted(set(new_files) - set(old_files))
    removed = sorted(set(old_files) - set(new_files))
    differing = sorted(name for name in set(old_files) & set(new_files)
                       if old_files[name]["sha256"].lower() != new_files[name]["sha256"].lower())
    files = {
        "added": added, "removed": removed,
        "changed": [{"path": name, "size_before": old_files[name]["size"], "size_after": new_files[name]["size"]}
                    for name in differing],
        "unchanged": len(set(old_files) & set(new_files)) - len(differing),
        "bytes_before": sum(item["size"] for item in old_files.values()),
        "bytes_after": sum(item["size"] for item in new_files.values()),
    }
    return {"names": names, "simulation": simulation, "search_meta": search, "analysis": analysis, "files": files}


