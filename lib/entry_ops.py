def reducing_end_anomer(glycam_name: str) -> Optional[str]:
    """``alpha`` or ``beta`` for a GLYCAM name that ends in ``a<n>-OH`` / ``b<n>-OH``; None otherwise."""
    match = _REDUCING_END.search(glycam_name or "")
    if match is None:
        return None
    return "alpha" if match.group(1) == "a" else "beta"


def with_anomer(glycam_name: str, anomer: str) -> str:
    """The GLYCAM name with the reducing end of ``anomer``; raises ValueError for a name without one."""
    match = _REDUCING_END.search(glycam_name or "")
    if match is None:
        raise ValueError(f"the GLYCAM name has no reducing end a<n>-OH or b<n>-OH: {str(glycam_name)[:80]!r}")
    if anomer not in ("alpha", "beta"):
        raise ValueError(f"the anomer is alpha or beta, not {anomer!r}")
    return glycam_name[:match.start()] + ("a" if anomer == "alpha" else "b") + match.group(2) + "-OH"


def simulated_anomer(topology_pdb: Path, reducing_residue: int = 2) -> Dict[str, Any]:
    """What the residue code of the reducing residue in ``topology.pdb`` says was simulated.

    GLYCAM codes name the anomer with their last letter (``4YA`` alpha,
    ``4YB`` beta); the reducing residue is residue 2, after ``ROH``.  The
    code is evidence, not proof: the chirality at C1 decides, and the
    administrator declares.  Returns ``{"residue", "anomer", "from"}`` with
    ``anomer`` None when the code says nothing.
    """
    residue = None
    try:
        with open(topology_pdb, "r", encoding="utf-8", errors="replace") as handle:
            for line in handle:
                if line.startswith(("ATOM  ", "HETATM")):
                    try:
                        number = int(line[22:26])
                    except ValueError:
                        continue
                    if number == reducing_residue:
                        residue = line[17:21].strip()
                        break
    except OSError:
        residue = None
    anomer = None
    if residue and residue[-1] in "AB" and len(residue) == 3:
        anomer = "alpha" if residue[-1] == "A" else "beta"
    return {"residue": residue, "anomer": anomer, "from": f"residue {reducing_residue} of topology.pdb"}


def _check_glycam_name(name: Any, what: str, errors: List[str]) -> str:
    if not isinstance(name, str) or not name or name != name.strip() or re.search(r"[\x00-\x1f\x7f]", name):
        errors.append(f"{what} must be a full GLYCAM name, not {name!r}")
        return ""
    try:
        archive.object_key_prefix(name)
    except archive.ArchiveError as exc:
        errors.append(f"{what}: {exc}")
        return ""
    return name


