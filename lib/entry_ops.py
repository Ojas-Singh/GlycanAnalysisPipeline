def renamed_manifest(manifest: Dict[str, Any], new_name: str, old_manifest_sha256: str, renamed_at: str,
                     reason: str, name_json: bytes) -> Dict[str, Any]:
    """The manifest of an archive entry under another GLYCAM name; the data files are the same.

    ``name.json`` (the authoritative name for the pipeline) is the one given;
    ``renamed_from`` records the old name, the SHA-256 of the old manifest
    and an earlier rename; an ``extends`` of the old manifest moves into
    ``renamed_from`` (it names the old entry).
    """
    renamed = copy.deepcopy(manifest)
    old_name = manifest["glycam_name"]
    renamed["glycam_name"] = new_name
    renamed["folder"] = archive.entry_folder_name(new_name)
    renamed["object_key_prefix"] = archive.object_key_prefix(new_name)
    files = dict(renamed["files"])
    files[archive.NAME_FILE] = {"size": len(name_json), "sha256": _sha256_bytes(name_json)}
    renamed["files"] = {name: files[name] for name in sorted(files, key=lambda item: (
        item not in (archive.TRAJECTORY_FILE, archive.TOPOLOGY_FILE, archive.MOL2_FILE), item))}
    renamed["renamed_from"] = {
        "glycam_name": old_name, "manifest_sha256": old_manifest_sha256, "renamed_at": renamed_at,
        "reason": reason, "extends": manifest.get("extends"), "previous": manifest.get("renamed_from"),
    }
    renamed.pop("extends", None)
    warnings = list(renamed.get("warnings") or [])
    warnings.append(f"renamed from {old_name[:120]} on {renamed_at}")
    renamed["warnings"] = warnings
    return renamed


def name_json_bytes(glycam_name: str) -> bytes:
    return _json_bytes({"indexOrderedSequence": glycam_name})


def write_renamed_entry(entry_dir: Path, dest_root: Path, new_name: str, renamed_at: str, reason: str) -> Path:
    """A local copy of an archive entry under ``new_name`` (data files hard-linked); returns its folder."""
    entry_dir = Path(entry_dir)
    manifest_bytes = (entry_dir / archive.MANIFEST_FILE).read_bytes()
    manifest = json.loads(manifest_bytes)
    name_json = name_json_bytes(new_name)
    renamed = renamed_manifest(manifest, new_name, _sha256_bytes(manifest_bytes), renamed_at, reason, name_json)
    final = Path(dest_root) / renamed["folder"]
    if final.exists():
        shutil.rmtree(final)
    final.mkdir(parents=True)
    for name in renamed["files"]:
        if name == archive.NAME_FILE:
            (final / name).write_bytes(name_json)
            continue
        try:
            os.link(entry_dir / name, final / name)
        except OSError:
            shutil.copyfile(entry_dir / name, final / name)
    (final / archive.MANIFEST_FILE).write_bytes(_json_bytes(renamed))
    return final


def index_with(stored: Optional[Dict[str, Any]], remove: Iterable[str],
               record: Optional[Dict[str, Any]]) -> Dict[str, Any]:
    """``raw/index.json`` without the records of ``remove`` and with ``record`` (inserted or replaced; None: none)."""
    removed = set(remove) | ({record["glycam_name"]} if record is not None else set())
    base = stored or {"schema": archive.INDEX_SCHEMA, "schema_version": archive.SCHEMA_VERSION,
                      "converter_version": archive.CONVERTER_VERSION, "records": []}
    records = [item for item in base["records"] if item["glycam_name"] not in removed] + ([record] if record else [])
    records.sort(key=lambda item: item["glycam_name"])
    index = dict(base)
    index.update(
        generated=_utc_now(),
        entries=len(records),
        totals={
            "frames": sum(item.get("frames") or 0 for item in records),
            "source_bytes": sum(item.get("source_size") or 0 for item in records),
            "archive_bytes": sum(item.get("archive_size") or 0 for item in records),
        },
        repaired=[item["glycam_name"] for item in records if "repaired" in item],
        records=records,
    )
    return index


def plan_raw_move(target: Target, store: Store, from_name: str, new_manifest_bytes: bytes,
                  local_dir: Optional[Path] = None, glycan_id: str = "", reason: str = ""
                  ) -> Tuple[Dict[str, Any], List[str]]:
    """What moving the raw entry ``from_name`` to the name of ``new_manifest_bytes`` takes; only reads.

    ``new_manifest_bytes`` is the manifest under the new name
    (:func:`renamed_manifest`).  Its data files are copied inside the
    storage from the old keys when they are stored there with the recorded
    content, otherwise uploaded from ``local_dir``; ``name.json`` and the
    manifest are written for the new name.  Returns ``(plan, refused)``;
    ``plan["relation"]`` is ``move``, ``moved`` (an earlier run finished the
    move; the index or the old keys may be left) or ``none``.
    """
    refused: List[str] = []
    new_manifest = json.loads(new_manifest_bytes)
    to_name = new_manifest["glycam_name"]
    try:
        from_prefix = archive_transfer.entry_key_prefix(target.raw_prefix, from_name)
        to_prefix = archive_transfer.entry_key_prefix(target.raw_prefix, to_name)
    except archive.ArchiveError as exc:
        return {}, [str(exc)]
    from_listing = store.list(from_prefix)
    to_listing = store.list(to_prefix)
    from_manifest = store.read_optional(from_prefix + archive.MANIFEST_FILE) \
        if from_prefix + archive.MANIFEST_FILE in from_listing else None
    to_manifest = store.read_optional(to_prefix + archive.MANIFEST_FILE) \
        if to_prefix + archive.MANIFEST_FILE in to_listing else None
    renamed_from = new_manifest.get("renamed_from") or {}
    old_sha256 = renamed_from.get("manifest_sha256")
    if from_manifest is not None and _sha256_bytes(from_manifest) != old_sha256:
        refused.append(f"the raw entry under {from_prefix[:100]} is not the one the rename was planned from "
                       "(its manifest changed): plan the operation again")
    if to_manifest is not None and to_manifest != new_manifest_bytes:
        refused.append(f"a raw entry of another glycan is stored under the new name ({to_prefix[:100]}): "
                       "a rename may not replace it")
    elif to_manifest is None and to_listing and from_manifest is None:
        refused.append(f"objects are stored under {to_prefix[:100]} without a manifest and the old entry is gone")
    if from_manifest is None and to_manifest is None:
        refused.append(f"no raw entry is stored under {from_prefix[:100]}")
    old = json.loads(from_manifest) if from_manifest is not None else None
    sources: List[Dict[str, Any]] = []
    for name, info in new_manifest["files"].items():
        item = {"name": name, "key": to_prefix + name, "size": info["size"], "sha256": info["sha256"]}
        if store.holds(item["key"], info["size"], info["sha256"]):
            item["how"] = "stored"
        elif old is not None and (old["files"].get(name) or {}).get("sha256") == info["sha256"] \
                and store.holds(from_prefix + name, info["size"], info["sha256"]):
            item.update(how="copy", source=from_prefix + name)
        elif name == archive.NAME_FILE:
            item.update(how="write", content=name_json_bytes(to_name).decode("utf-8"))
            if _sha256_bytes(name_json_bytes(to_name)) != info["sha256"]:
                refused.append("name.json of the new manifest is not the one of the new name")
        elif local_dir is not None and (Path(local_dir) / name).is_file():
            item.update(how="upload", path=str(Path(local_dir) / name))
        else:
            refused.append(f"{name} of the renamed entry is neither stored under the old name nor here")
            item["how"] = "missing"
        sources.append(item)
    history_root = f"{target.history(from_name)}{old_sha256}/"
    history = []
    if from_manifest is not None:
        history.append({"source": from_prefix + archive.MANIFEST_FILE, "key": history_root + archive.MANIFEST_FILE})
        if from_prefix + archive.NAME_FILE in from_listing:
            history.append({"source": from_prefix + archive.NAME_FILE, "key": history_root + archive.NAME_FILE})
    index_key = f"{target.raw_prefix}/{archive.INDEX_FILE}"
    stored_index_bytes = store.read_optional(index_key)
    stored_index = None
    if stored_index_bytes is not None:
        try:
            stored_index = archive_transfer.parse_index(stored_index_bytes, f"the stored {index_key}")
        except archive_transfer.TransferError as exc:
            refused.append(str(exc))
    manifest_sha256 = _sha256_bytes(new_manifest_bytes)
    record = entry_publish.index_record(new_manifest, len(new_manifest_bytes), manifest_sha256)
    index = index_with(stored_index, [from_name], record)
    listed = {item["glycam_name"] for item in (stored_index or {}).get("records", [])}
    index_changes = from_name in listed or (stored_index or {}).get("records", []) != index["records"]
    relation = "moved" if to_manifest == new_manifest_bytes and from_manifest is None else "move"
    plan = {
        "relation": relation,
        "from_name": from_name, "to_name": to_name,
        "from_key_prefix": from_prefix, "to_key_prefix": to_prefix,
        "files": sources,
        "manifest": {"key": to_prefix + archive.MANIFEST_FILE, "size": len(new_manifest_bytes),
                     "sha256": manifest_sha256, "content": new_manifest_bytes.decode("utf-8")},
        "manifest_stored": to_manifest == new_manifest_bytes,
        "history": history,
        "rename_record_key": history_root + "renamed.json",
        "rename_record": {
            "schema": RENAME_SCHEMA, "schema_version": 1, "from": from_name, "to": to_name,
            "glycoshape_id": glycan_id, "renamed_at": renamed_from.get("renamed_at"), "reason": reason,
            "manifest_sha256_before": old_sha256, "manifest_sha256_after": manifest_sha256,
            "to_key_prefix": to_prefix,
        },
        "delete": sorted(from_listing),
        "index_key": index_key,
        "index": index,
        "index_changes": index_changes,
    }
    return plan, refused


def describe_raw_move(plan: Dict[str, Any]) -> Dict[str, Any]:
    return {
        "relation": plan["relation"],
        "from_key_prefix": plan["from_key_prefix"],
        "to_key_prefix": plan["to_key_prefix"],
        "copy": [item["name"] for item in plan["files"] if item["how"] == "copy"],
        "upload": [item["name"] for item in plan["files"] if item["how"] in ("upload", "write")]
        + ([] if plan["manifest_stored"] else [archive.MANIFEST_FILE]),
        "unchanged": [item["name"] for item in plan["files"] if item["how"] == "stored"],
        "upload_bytes": sum(item["size"] for item in plan["files"] if item["how"] in ("upload", "write"))
        + (0 if plan["manifest_stored"] else plan["manifest"]["size"]),
        "copy_bytes": sum(item["size"] for item in plan["files"] if item["how"] == "copy"),
        "history": [item["key"] for item in plan["history"]] + [plan["rename_record_key"]],
        "delete": plan["delete"],
        "index": f"{plan['index']['entries']} entries" if plan["index_changes"] else "unchanged",
    }


def publish_raw_move(target: Target, store: Store, plan: Dict[str, Any], log: Log = print,
                     checkpoint: Callable[[str], None] = _noop) -> None:
    """Move the raw entry as planned; every step skips what is done, so it can be run again.

    1. the old manifest (and ``name.json``) to the history, with ``renamed.json``;
    2. the data files to the new keys (copies inside the storage), ``name.json``;
    3. the new manifest, last of the new entry: from here the entry is complete under its new name;
    4. ``raw/index.json`` lists the new name and not the old one;
    5. the old keys are deleted, the manifest first.
    """
    try:
        for item in plan["history"]:
            head = store.head(item["source"])
            if store.head(item["key"]) is None and head is not None:
                store.copy(item["source"], item["key"], head["size"], head["sha256"])
        record = _json_bytes(plan["rename_record"])
        if store.read_optional(plan["rename_record_key"]) != record:
            store.write(plan["rename_record_key"], record)
        checkpoint("move:history")
        for item in plan["files"]:
            if store.holds(item["key"], item["size"], item["sha256"]):
                continue
            if item["how"] == "copy" and store.holds(item["source"], item["size"], item["sha256"]):
                store.copy(item["source"], item["key"], item["size"], item["sha256"])
            elif item["how"] == "write":
                store.write(item["key"], item["content"].encode("utf-8"))
            elif item["how"] == "upload":
                store.upload(Path(item["path"]), item["key"], item["size"], item["sha256"])
            else:
                raise OperationError(f"{item['name']} of the renamed entry cannot be stored: its source is gone")
            checkpoint(f"move:{item['name']}")
        manifest = plan["manifest"]
        if not store.holds(manifest["key"], manifest["size"], manifest["sha256"]):
            store.write(manifest["key"], manifest["content"].encode("utf-8"))
        checkpoint("move:manifest")
        current = store.read_optional(plan["index_key"])
        wanted = {item["glycam_name"] for item in plan["index"]["records"]}
        stale = current is None or plan["from_name"] in {
            item["glycam_name"] for item in json.loads(current).get("records", [])} or plan["to_name"] not in {
            item["glycam_name"] for item in json.loads(current).get("records", [])}
        if plan["index_changes"] and stale and plan["to_name"] in wanted:
            store.write(plan["index_key"], _json_bytes(plan["index"]))
        checkpoint("move:index")
        doomed = sorted(store.list(plan["from_key_prefix"]))
        old_manifest = plan["from_key_prefix"] + archive.MANIFEST_FILE
        if old_manifest in doomed:
            store.delete(old_manifest)
            doomed.remove(old_manifest)
        for _ in parallel_map(store.delete, doomed, target.workers):
            pass
        checkpoint("move:deleted")
    except (PublishEntryError, KeyboardInterrupt):
        raise
    except Exception as exc:
        raise OperationError(
            f"the raw entry was not moved completely ({type(exc).__name__}: {exc}); the published database has not "
            "changed; run the command again to continue") from exc
    log(f"raw entry moved: {plan['from_key_prefix'][:80]} -> {plan['to_key_prefix'][:80]}")


