def update_metadata(
    changes: Any,
    target: Target,
    work_dir,
    policy: Optional[Policy] = None,
    dry_run: bool = False,
    offline: Optional[bool] = None,
    lookup_timeout: Optional[float] = None,
    lookup_budget: Optional[float] = 300.0,
    refresh: bool = False,
    expect_hash: Optional[str] = None,
    lock_ttl: float = entry_publish.DEFAULT_LOCK_TTL,
    break_lock: bool = False,
    cache_dir=None,
    owner: Optional[str] = None,
    log: Log = print,
    checkpoint: Callable[[str], None] = _noop,
) -> Dict[str, Any]:
    """Publish the stored entry again with the curated metadata changed, without a new analysis.

    The stored folder is downloaded and verified, turned back into its
    static-ready form (:func:`static_ready_from_folder`) and completed with
    the submission and curation after ``changes`` (:class:`Changes`), as a
    new entry is completed.  A new GLYCAM name moves the raw entry
    (:func:`plan_raw_move`).  The result is published as a ``replace`` with
    a record in the history.  ``expect_hash`` is the folder hash of the dry
    run that was approved.  Returns the report (:data:`REPORT_SCHEMA`);
    raises as ``entry_publish.publish_entry``.
    """
    changes = Changes.parse(changes)
    policy = policy or Policy()
    owner = owner or entry_publish.new_owner()
    started = time.perf_counter()
    stats = entry_publish.new_stats()
    static_store = Store(target.static, stats, dry_run)
    raw_store = Store(target.raw, stats, dry_run)
    work = Path(work_dir)
    work.mkdir(parents=True, exist_ok=True)
    glycan_id = changes.glycoshape_id
    report = _new_report(UPDATE_METADATA, glycan_id, dry_run, owner, work, stats)
    report["changes"] = changes.record()
    journal: Optional[entry_publish.Journal] = None
    try:
        with _locked(target, static_store, owner, UPDATE_METADATA, glycan_id, lock_ttl, break_lock, dry_run,
                     report, log, checkpoint) as lock:
            database = entry_publish.read_database(target, static_store, work, cache_dir)
            published = read_published(target, static_store, raw_store, database, glycan_id)
            new_name = changes.glycam_name or published.published_name
            report.update(glycam_name=new_name, previous_glycam_name=published.published_name)
            journal = entry_publish.Journal(work, UPDATE_METADATA, glycan_id, new_name, owner)
            journal.save()
            refused: List[str] = []
            renamed_already = changes.glycam_name is not None and published.published_name == changes.glycam_name
            if changes.expect_glycam_name is not None and changes.expect_glycam_name not in (
                    published.published_name, published.raw_name) and not renamed_already:
                refused.append(f"{glycan_id} is published as {published.published_name[:80]}, the changes were made "
                               f"for {changes.expect_glycam_name[:80]}")
            if changes.expect_folder_hash is not None and changes.expect_folder_hash != published.folder_hash:
                refused.append(f"the stored folder of {glycan_id} changed since the changes were made (hash "
                               f"{published.folder_hash[:16]}..., they were made for {changes.expect_folder_hash[:16]}...)")
            renamed = new_name != published.published_name
            raw_move = renamed and new_name != published.raw_name
            if renamed:
                refused += check_new_name(database, published, new_name)
                before, after = reducing_end_anomer(published.raw_name), reducing_end_anomer(new_name)
                if before and after and before != after:
                    refused.append(
                        f"the new name declares the {after} anomer and the stored analysis was made for the {before} "
                        "anomer: which file holds the simulated structure depends on it, so use reanalyse "
                        "--simulated-anomer instead")
            levels = tuple(policy.levels) if policy.levels is not None else _configured_levels()

            # The stored folder, as the static-ready one it was completed from.
            stored = download_folder(target, static_store, database, glycan_id, work / "stored")
            ready = static_ready_from_folder(stored, work / "static-ready", levels)
            report["stored_folder"] = {"hash": published.folder_hash, "left_out": ready["left_out"],
                                       "kept_with_identifier_block": ready["kept_with_block"]}
            if ready["kept_with_block"]:
                report["warnings"].append(
                    f"{len(ready['kept_with_block'])} PDB file(s) do not start with the GlycoShape REMARK block this "
                    f"code writes and are kept as they are, first {ready['kept_with_block'][0]}")
            unknown = [name for name in ready["left_out"] if name not in (
                "data.json", "snfg.svg", "glygen.json", "glycosmos.json", f"{glycan_id}.zip")]
            if unknown:
                report["warnings"].append(f"{len(unknown)} stored file(s) are not part of a folder this code writes "
                                          f"and are left out: {', '.join(unknown[:5])}")
            base_submission, curation, notes = published_submission(published.data, published.published_name,
                                                                     published.record)
            report["curated_from"] = notes
            submission_record, curation = apply_changes(base_submission, curation, changes,
                                                        published.published_name, new_name)
            submission_record["glycoshape_id"] = glycan_id
            try:
                submission = entry_complete.Submission.parse(submission_record)
            except entry_complete.SubmissionError as exc:
                raise Refused(str(exc)) from exc

            def complete() -> Dict[str, Any]:
                output = work / "static"
                folder, data, summary = entry_complete.complete_folder(
                    work / "static-ready", new_name, levels, submission, output, offline=offline,
                    lookup_timeout=lookup_timeout, lookup_budget=lookup_budget, names=curation["names"],
                    aliases=curation.get("aliases") or [], keywords=curation.get("keywords") or {},
                    public_note=curation.get("public_note") or "", salt_by_run=curation.get("salt_by_run"))
                return entry_complete.folder_report(folder, data, levels, summary, submission, list(submission.warnings))

            ready_hash = _tree_hash(work / "static-ready")
            fingerprint = hashlib.sha256(json.dumps(
                [ready_hash, submission.sha256(), curation, list(levels), new_name], sort_keys=True).encode()).hexdigest()
            entry = _cached_completion(work, journal, fingerprint, refresh, log, complete)
            folder = Path(entry["folder"])
            report["entry"] = _entry_summary(entry)
            report["warnings"] += entry["warnings"]
            if entry["problems"] and not policy.allow_incomplete:
                refused += [f"the entry is not complete: {problem}" for problem in entry["problems"]]
            if expect_hash is not None and expect_hash != entry["hash"]:
                refused.append(f"the folder has the hash {entry['hash'][:16]}... and {expect_hash[:16]}... was approved")
            new_data = json.loads((folder / "data.json").read_bytes())
            report["diff"] = diff_entry(published.data, new_data, published.files, entry["files"])
            report["database"] = {"global_hash": database.global_hash, "glycans": len(database.manifest["glycans"]),
                                  "withdrawn": len(database.withdrawn)}

            raw: Dict[str, Any] = {"kind": "none"}
            report["rename"] = None
            if renamed:
                report["rename"] = {"from": published.published_name, "to": new_name, "raw": None,
                                    "old_name_kept_as_alias": changes.keep_old_name_as_alias}
            if raw_move:
                move = _plan_move_from_storage(target, raw_store, published, new_name, journal, changes.curator_note
                                               or "update-metadata", work)
                if move is None:
                    report["warnings"].append(f"no raw entry is stored for {published.raw_name[:80]}: only the "
                                              "published name changes")
                else:
                    plan, move_refused = move
                    refused += move_refused
                    if plan:
                        raw = {"kind": "move", "plan": plan}
                        report["rename"]["raw"] = describe_raw_move(plan)
            elif renamed:
                report["rename"]["raw"] = {"relation": "already-named" if new_name == published.raw_name else "none",
                                           "key_prefix": _raw_prefix_or_none(target, new_name)}
            record_extra = {
                "operation": UPDATE_METADATA, "changes": changes.record(), "curation": curation,
                "curator_note": changes.curator_note, "author": changes.author,
                "raw_manifest_sha256": None,
            }
            report = publish_version(
                UPDATE_METADATA, target, work, journal, (static_store, raw_store), database, published, folder,
                {**entry, "glycam_name": new_name}, report, refused, raw, record_extra, owner, lock, lock_ttl,
                dry_run, offline, cache_dir, None, log, checkpoint)
    except Refused as exc:
        if not report["refused"]:
            entry_publish._refusal(report, [str(exc)] if not exc.report else exc.report.get("refused") or [str(exc)])
        if not dry_run:
            exc.report = report
            raise
    return _finish(report, journal, started, dry_run, stats)


def _configured_levels() -> Tuple[int, ...]:
    import lib.config as config

    return tuple(config.cluster_levels)


def _tree_hash(folder: Path) -> str:
    digest = hashlib.sha256()
    for path in sorted(p for p in Path(folder).rglob("*") if p.is_file()):
        size, sha = file_sha256(path)
        digest.update(f"{path.relative_to(folder).as_posix()}\0{sha}\0{size}\n".encode())
    return digest.hexdigest()


def _raw_prefix_or_none(target: Target, name: str) -> Optional[str]:
    try:
        return archive_transfer.entry_key_prefix(target.raw_prefix, name)
    except archive.ArchiveError:
        return None


def _plan_move_from_storage(target: Target, raw_store: Store, published: Published, new_name: str,
                            journal: entry_publish.Journal, reason: str, work: Path
                            ) -> Optional[Tuple[Dict[str, Any], List[str]]]:
    """The move of the stored raw entry to ``new_name``, built from its stored manifest; None without one."""
    from_prefix = archive_transfer.entry_key_prefix(target.raw_prefix, published.raw_name)
    to_prefix = archive_transfer.entry_key_prefix(target.raw_prefix, new_name)
    kept = journal.data.get("raw_move")
    if kept and kept.get("from") == published.raw_name and kept.get("to") == new_name:
        manifest_bytes = kept["manifest"].encode("utf-8")      # the manifest planned by an earlier run
    else:
        stored = raw_store.read_optional(from_prefix + archive.MANIFEST_FILE)
        if stored is None:
            moved = raw_store.read_optional(to_prefix + archive.MANIFEST_FILE)
            if moved is not None and (json.loads(moved).get("renamed_from") or {}).get("glycam_name") == published.raw_name:
                manifest_bytes = moved                               # moved by an earlier run of another work folder
            else:
                return None
        else:
            manifest = json.loads(stored)
            renamed = renamed_manifest(manifest, new_name, _sha256_bytes(stored), journal.data["started"], reason,
                                       name_json_bytes(new_name))
            manifest_bytes = _json_bytes(renamed)
        journal.data["raw_move"] = {"from": published.raw_name, "to": new_name,
                                    "manifest": manifest_bytes.decode("utf-8")}
        journal.save()
    return plan_raw_move(target, raw_store, published.raw_name, manifest_bytes, None, published.glycan_id, reason)


