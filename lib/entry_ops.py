# The stored folder as a static-ready one
# ---------------------------------------------------------------------------
def download_folder(target: Target, store: Store, database: entry_publish.Database, glycan_id: str, dest: Path,
                    only: Optional[Iterable[str]] = None) -> Path:
    """The stored ``static/GSxxxxx/`` (or the files of it named in ``only``) in ``dest/GSxxxxx``, verified."""
    entry = database.manifest["glycans"].get(glycan_id)
    if entry is None:
        raise Refused(f"{glycan_id} is not published")
    folder = Path(dest) / glycan_id
    wanted = set(only) if only is not None else None

    def fetch(item: Tuple[str, Dict[str, Any]]) -> str:
        relative, info = item
        local = folder / relative
        recorded = (info["size"], info["sha256"].lower())
        if local.is_file() and file_sha256(local) == recorded:
            return relative
        local.parent.mkdir(parents=True, exist_ok=True)
        part = local.with_name(local.name + ".part")
        store.download(target.key(info["path"]), part)
        if file_sha256(part) != recorded:
            part.unlink()
            raise OperationError(f"{target.key(info['path'])} is not the file the stored manifest describes")
        os.replace(part, local)
        return relative

    items = [(relative, info) for relative, info in sorted(entry["files"].items())
             if wanted is None or relative in wanted]
    for _ in parallel_map(fetch, items, target.workers):
        pass
    return folder


def strip_identifier_remarks(text: str) -> Optional[str]:
    """The PDB text without the GlycoShape REMARK block at its top; None when it does not start with one."""
    if not text.startswith(_REMARK_BANNER):
        return None
    index = text.find("\n" + _STATIC_READY_FIRST_LINE)
    return None if index < 0 else text[index + 1:]


def _identifier_values(text: str) -> Tuple[Optional[str], Optional[str]]:
    glytoucan = iupac = None
    for line in text.splitlines():
        if line.startswith(_STATIC_READY_FIRST_LINE):
            break
        if line.startswith("REMARK    GlyTouCan ID: "):
            glytoucan = line[len("REMARK    GlyTouCan ID: "):]
        elif line.startswith("REMARK    IUPAC Name: "):
            iupac = line[len("REMARK    IUPAC Name: "):]
    return glytoucan, iupac


def static_ready_from_folder(folder: Path, dest: Path, levels: Iterable[int]) -> Dict[str, Any]:
    """The static-ready folder a published one was completed from, in ``dest``.

    The analysis files are taken as they are (hard links where possible);
    the PDB files lose the GlycoShape REMARK block, and only when putting the
    same block back gives the stored file byte for byte.  Returns what was
    taken, what was left out (the files the completion writes again) and the
    PDB files whose block could not be taken off (kept unchanged, reported).
    """
    from lib import glypdbio, replicas, static_levels, static_ready

    folder, dest = Path(folder), Path(dest)
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    levels = tuple(levels)
    taken: List[str] = []
    kept_with_block: List[str] = []
    level_files = [f"output/level_{level}/{name}" for level in levels for name in static_levels.LEVEL_FILES]
    tables = [f"output/{name}" for name in static_ready.ANALYSIS_TABLES]
    tables += [f"output/torsion_level_{level}_reps.csv" for level in levels]
    plain = tables + ["output/torparts.npz", "output/info.json", replicas.STATIC_PATH]
    plain += [f"landscape/{name}" for name in static_ready.LANDSCAPE_FILES]

    def link(relative: str) -> None:
        source, target = folder / relative, dest / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        try:
            os.link(source, target)
        except OSError:
            shutil.copyfile(source, target)
        taken.append(relative)

    for relative in level_files:
        source = folder / relative
        if not source.is_file():
            continue
        if not relative.endswith(".pdb"):
            link(relative)
            continue
        text = source.read_text(encoding="utf-8")
        stripped = strip_identifier_remarks(text)
        target = dest / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        if stripped is not None:
            glytoucan, iupac = _identifier_values(text)
            target.write_text(stripped, encoding="utf-8")
            glypdbio._add_pdb_remarks(str(target), glytoucan_id=glytoucan, iupac=iupac)
            if target.read_bytes() == source.read_bytes():
                target.write_text(stripped, encoding="utf-8")
                taken.append(relative)
                continue
        target.unlink(missing_ok=True)
        link(relative)
        kept_with_block.append(relative)
    for relative in plain:
        if (folder / relative).is_file():
            link(relative)
    present = sorted(path.relative_to(folder).as_posix() for path in folder.rglob("*") if path.is_file())
    left_out = [relative for relative in present if relative not in taken]
    return {"taken": sorted(taken), "left_out": left_out, "kept_with_block": kept_with_block}


