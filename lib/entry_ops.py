"""Operations on published entries: change the curated metadata, re-analyse, rename.

The published database is always derived: from the raw archive entry of a
glycan (``raw/<GLYCAM name>/``), the analysis code and the curated metadata
of its GlycoShape ID.  An administrator's action on a published entry is
therefore a new version of its folder ``static/GSxxxxx/``, published like a
``replace`` (``lib.entry_publish``: staging, the switch, ``sync_manifest.json``
last), with a record of the version kept in the storage:

``update-metadata`` (:func:`update_metadata`)
    The stored folder with other curated metadata and no new analysis:
    names, accessions, keywords, simulation metadata, a note.  Everything
    that follows from the names (WURCS, IUPAC, SNFG image, mass, the row of
    the inventory, ``GSxxxxx.zip``, the RDF) is derived again with the
    functions the static stage uses.  The input is a *changes* record
    (:class:`Changes`, schema ``glycoshape-entry-changes``).

``reanalyse`` (:func:`reanalyse`)
    The analysis of the stored raw entry again, with this code: optionally
    without some replicas, and with the anomer that was simulated declared.

``merge`` (:func:`merge`)
    One GlycoShape ID per simulated glycan: a glycan published under two
    IDs (two simulations, two GLYCAM names that differ in the order the
    branches are written in) keeps one.  The raw entry of the kept ID gets
    the frames of the other (``lib.archive_segments.merge_entries``), the
    union is analysed and published as a new version of the kept ID, and
    in the same command the absorbed ID is withdrawn (its tombstone says
    ``merged_into``) and its raw entry moves to the history.

Renames
-------
The raw archive is keyed by the GLYCAM name, and so is everything that looks
an entry up (publishing, extension, ``raw/index.json``).  A new GLYCAM name
therefore **moves** the raw entry (:func:`plan_raw_move`): its data files are
copied inside the storage to ``raw/<new name>/`` (no data passes through this
machine), ``name.json`` and ``manifest.json`` are written for the new name
(the manifest records ``renamed_from``: the old name and the SHA-256 of the
old manifest), the index lists the new name instead of the old one, and the
old keys are deleted.  The old manifest stays in the history,
``raw-history/<raw prefix>/<old name>/<its SHA-256>/manifest.json``, next to
``renamed.json``, which says where the entry went.  The old name becomes a
search alias of the entry unless the changes say otherwise.

A rename is refused when the new name is published (or was withdrawn) under
another GlycoShape ID, or when a raw entry of another glycan is stored under
it.  A rename that changes the anomer of the reducing end is refused by
``update-metadata``: which file holds the simulated structure depends on it,
so it is ``reanalyse --simulated-anomer`` (problem list, section 1: entries
declared ``...b1-OH`` that were simulated as the alpha anomer).

Version history
---------------
Every publication of an entry (also ``publish``, ``replace`` and
``withdraw``) leaves ``publish-state/<static prefix>/history/GSxxxxx/<time>-<action>.json``:
what was done, by which code, from which raw manifest, with which changes and
note, and the folder hash before and after.  Together with the raw history
this is enough to derive any earlier version again.
"""
