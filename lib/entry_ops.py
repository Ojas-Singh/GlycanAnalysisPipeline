def _cached_completion(work: Path, journal: entry_publish.Journal, fingerprint: str, refresh: bool, log: Log,
                       complete: Callable[[], Dict[str, Any]]) -> Dict[str, Any]:
    """The completed folder of an earlier run of the same operation, or a new one (as ``entry_publish._complete``)."""
    kept = journal.data["steps"].get("complete") or {}
    report_path = work / "entry.json"
    if not refresh and kept.get("fingerprint") == fingerprint and report_path.is_file():
        try:
            report = json.loads(report_path.read_bytes())
        except ValueError:
            report = None
        folder = Path(report["folder"]) if report else None
        if report is not None and folder.is_dir() and static_delta.folder_entry(folder)["hash"] == kept.get("hash"):
            if not report.get("problems"):
                log(f"using the folder completed at {kept['at']} ({folder})")
                return report
            log(f"the folder completed at {kept['at']} was not complete ({'; '.join(report['problems'])}): "
                "completing it again")
    report = complete()
    report["hash"] = static_delta.folder_entry(Path(report["folder"]))["hash"]
    _write_json(report_path, report)
    journal.step("complete", fingerprint=fingerprint, hash=report["hash"], files=report["file_count"],
                 bytes=report["total_size"], offline=report["lookups"]["offline"],
                 unanswered=report["lookups"]["unanswered"], problems=report["problems"])
    log(f"completed {Path(report['folder']).name}: {report['file_count']} files, {report['total_size'] / 1e6:.1f} MB; "
        f"{len(report['gaps'])} empty identity field(s), {len(report['lookups']['unanswered'])} lookup(s) unanswered")
    return report


def publish_version(
    operation: str,
    target: Target,
    work: Path,
    journal: entry_publish.Journal,
    stores: Tuple[Store, Store],
    database: entry_publish.Database,
    published: Published,
    folder: Path,
    entry: Dict[str, Any],
    report: Dict[str, Any],
    refused: List[str],
    raw: Dict[str, Any],
    record_extra: Dict[str, Any],
    owner: str,
    lock: Optional[Dict[str, Any]],
    lock_ttl: float,
    dry_run: bool,
    offline: Optional[bool],
    cache_dir: Optional[Path],
    bundle: Optional[entry_complete.Bundle],
    log: Log,
    checkpoint: Callable[[str], None],
) -> Dict[str, Any]:
    """Derive, plan and (unless a dry run) publish the new folder of a published entry as a ``replace``.

    ``raw`` is ``{"kind": "none"}`` (the raw entry stays), ``{"kind":
    "bundle", "plan": ...}`` (``entry_publish.plan_raw`` of the bundle: the
    same raw entry) or ``{"kind": "move", "plan": ...}``
    (:func:`plan_raw_move`).  ``refused`` collects the reasons not to
    publish; with any of them a dry run returns the report and a real run
    raises :class:`Refused`.
    """
    static_store, raw_store = stores
    glycan_id = published.glycan_id
    new_name = entry["glycam_name"]
    if refused:
        journal.data["status"] = "refused"
        journal.save()
        failure = entry_publish._refusal(report, refused)
        if dry_run:
            return report
        raise failure
    stored_entry = database.manifest["glycans"][glycan_id]
    already = stored_entry.get("hash") == entry["hash"] and raw["kind"] != "move" \
        and published.published_name == new_name
    if already:
        report["status"] = "already-published"
        report["static"] = {"base_global_hash": database.global_hash, "target_global_hash": database.global_hash}
    else:
        def fetch(other_id: str) -> Optional[bytes]:
            return static_store.read_optional(target.key(f"{other_id}/{other_id}.zip"))

        try:
            derived_dir, derived = entry_publish._derive(
                entry_publish.REPLACE, glycan_id, database, folder, work, journal, journal.data["started"], fetch,
                offline, log)
        except static_delta.DeltaError as exc:
            failure = entry_publish._refusal(report, [str(exc)])
            if dry_run:
                return report
            raise failure from exc
        static_plan = entry_publish.plan_static(target, static_store, database, entry_publish.REPLACE, glycan_id,
                                                folder, derived_dir, derived)
        report["static"] = entry_publish.describe_static(static_plan)
        report["master_archive"] = derived["master_archive"]
        report["status"] = "planned"
        if not dry_run:
            if raw["kind"] == "move":
                publish_raw_move(target, raw_store, raw["plan"], log, checkpoint)
                journal.step("raw", relation="move", to=raw["plan"]["to_key_prefix"])
            elif raw["kind"] == "bundle":
                plan = raw["plan"]
                if not (plan["relation"] == "same" and not plan["index_changes"] and not plan["stale"]):
                    entry_publish.publish_raw(target, raw_store, plan, log, checkpoint)
                journal.step("raw", relation=plan["relation"])
            record = entry_publish._entry_record(operation, glycan_id, new_name, owner, database.global_hash,
                                                 derived["global_hash"], entry, report)
            record.update(record_extra)
            history = {
                "key": target.history_key(glycan_id, derived["global_hash"], operation),
                "document": {**record, "kind": "version", "folder_hash_before": published.folder_hash,
                             "glycam_name_before": published.published_name},
            }
            done = entry_publish.publish_static(
                target, static_store, static_plan,
                {"glycam_name": new_name, "record": record, "history": history, "withdrawn": None},
                owner, lock, lock_ttl, log, checkpoint)
            journal.step("static", base_global_hash=database.global_hash, global_hash=derived["global_hash"], **done)
            report["switch"] = done
            report["history"] = {"key": history["key"]}
            entry_publish._remember(cache_dir, derived_dir, derived)
            report["status"] = "published"
    if bundle is not None:
        kept = entry_publish.keep_replicas(target, static_store, bundle, glycan_id, dry_run, log)
        if kept is not None:
            report["replicas"] = kept
    return report


@contextlib.contextmanager
def _locked(target: Target, store: Store, owner: str, action: str, glycan_id: str, lock_ttl: float,
            break_lock: bool, dry_run: bool, report: Dict[str, Any], log: Log, checkpoint: Callable[[str], None]):
    """The lock of the database for a real run (and any interrupted publication completed first)."""
    with contextlib.ExitStack() as stack:
        lock = None
        if not dry_run:
            stack.enter_context(entry_publish._in_process(target))
            lock = entry_publish.acquire_lock(target, store, owner, action, glycan_id, lock_ttl, break_lock, log)
            stack.callback(lambda: entry_publish._release_quietly(target, store, lock, log))
            report["conditional_writes"] = target._conditional
            pending = entry_publish.read_pending(target, store)
            if pending is not None:
                log(f"completing the interrupted {pending['action']} of {pending['glycoshape_id']} (by {pending['owner']})")
                entry_publish.roll_forward(target, store, pending, log, checkpoint)
        else:
            other, pending = entry_publish.read_lock(target, store), entry_publish.read_pending(target, store)
            report["lock"] = other
            if other is not None and not entry_publish._is_past(other.get("expires")):
                report["warnings"].append(f"the database is locked by {other.get('owner')} until {other.get('expires')}")
            if pending is not None:
                raise Refused(f"an interrupted {pending['action']} of {pending['glycoshape_id']} is pending; it is "
                              "completed by the next publication or by publish_entry.py recover")
        yield lock


def _new_report(operation: str, glycan_id: str, dry_run: bool, owner: str, work: Path,
                stats: Dict[str, Any]) -> Dict[str, Any]:
    return {
        "schema": REPORT_SCHEMA, "schema_version": REPORT_SCHEMA_VERSION, "operation": operation,
        "action": entry_publish.REPLACE, "glycoshape_id": glycan_id, "glycam_name": None,
        "previous_glycam_name": None, "dry_run": dry_run, "ok": True, "status": None, "owner": owner,
        "work_dir": str(work), "refused": [], "warnings": [], "transfers": stats,
    }


def _finish(report: Dict[str, Any], journal: Optional[entry_publish.Journal], started: float, dry_run: bool,
            stats: Dict[str, Any]) -> Dict[str, Any]:
    report["seconds"] = round(time.perf_counter() - started, 3)
    if journal is not None:
        journal.data["status"] = "dry-run" if dry_run else report.get("status") or "stopped"
        journal.data["transfers"] = stats
        journal.save()
    return report


def _entry_summary(entry: Dict[str, Any]) -> Dict[str, Any]:
    return {key: entry.get(key) for key in (
        "hash", "file_count", "total_size", "identity", "simulation", "search_meta", "gaps", "problems", "lookups")}


