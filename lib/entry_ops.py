@dataclass(frozen=True)
class Changes:
    """What an administrator changes about a published entry; see :meth:`parse` for the record.

    Every field is optional; what is absent stays as it is.  ``names`` are
    overrides of what is derived from the GLYCAM name (an empty text removes
    an override), ``glytoucan`` accessions per variant, ``curated`` replaces
    the curated lists and description it names, ``keywords`` edits the
    keywords, ``simulation`` replaces the simulation fields it names (each
    with its unit in its name).  ``curator_note`` is kept in the history of
    the entry; ``public_note`` is shown with it (an empty text removes it).
    """

    glycoshape_id: str
    expect_glycam_name: Optional[str] = None
    expect_folder_hash: Optional[str] = None
    glycam_name: Optional[str] = None
    keep_old_name_as_alias: bool = True
    names: Dict[str, str] = field(default_factory=dict)
    glytoucan: Dict[str, str] = field(default_factory=dict)
    curated: Dict[str, Any] = field(default_factory=dict)
    keywords: Dict[str, List[str]] = field(default_factory=dict)
    simulation: Dict[str, Any] = field(default_factory=dict)
    curator_note: str = ""
    public_note: Optional[str] = None
    author: str = ""

    @classmethod
    def parse(cls, record: Any) -> "Changes":
        """The changes of a JSON record; raises ``entry_complete.SubmissionError`` naming every problem.

        ::

            {
              "schema": "glycoshape-entry-changes", "schema_version": 1,
              "glycoshape_id": "GS00020",
              "expect": {"glycam_name": "...", "folder_hash": "..."},
              "names": {"glycam_name": "...", "keep_old_name_as_alias": true,
                        "iupac": "...", "alpha_glycam": "...", "beta_glycam": "...",
                        "alpha_iupac": "...", "beta_iupac": "..."},
              "glytoucan": {"archetype": "G00001AA", "alpha": "...", "beta": "..."},
              "curated": {"common_names": [...], "aliases": [...], "description": "..."},
              "keywords": {"add": [...], "remove": [...]}       or {"replace": [...]},
              "simulation": {"simulation_length_ns": 2500, "md_package": "GROMACS", "force_field": "GLYCAM_06j",
                             "water_model": "TIP3P", "temperature_k": 300, "pressure_bar": 1,
                             "salt_concentration_mm": 150, "source_type": "...", "comments": "..."},
              "curator_note": "kept in the history", "public_note": "shown with the entry",
              "author": "who asked"
            }
        """
        SubmissionError = entry_complete.SubmissionError
        if isinstance(record, Changes):
            return record
        if not isinstance(record, dict):
            raise SubmissionError("the changes record is not a JSON object")
        errors: List[str] = []
        if record.get("schema") != CHANGES_SCHEMA:
            errors.append(f"schema is {record.get('schema')!r}, expected {CHANGES_SCHEMA!r}")
        if record.get("schema_version") != CHANGES_SCHEMA_VERSION:
            errors.append(f"schema_version is {record.get('schema_version')!r}, this code reads {CHANGES_SCHEMA_VERSION}")
        known = ("schema", "schema_version", "glycoshape_id", "expect", "names", "glytoucan", "curated", "keywords",
                 "simulation", "curator_note", "public_note", "author")
        errors += [f"unknown field {key!r}" for key in sorted(set(record) - set(known))]
        glycoshape_id = record.get("glycoshape_id")
        if not isinstance(glycoshape_id, str) or not _GLYCOSHAPE_ID.match(glycoshape_id):
            errors.append(f"glycoshape_id must be GS and five digits, not {glycoshape_id!r}")
            glycoshape_id = ""

        def section(name: str, keys: Iterable[str]) -> Dict[str, Any]:
            value = record.get(name, {})
            if value is None:
                return {}
            if not isinstance(value, dict):
                errors.append(f"{name} must be an object")
                return {}
            errors.extend(f"unknown field {name}.{key}" for key in sorted(set(value) - set(keys)))
            return value

        def text(value: Any, what: str) -> str:
            if value is None:
                return ""
            if not isinstance(value, str):
                errors.append(f"{what} must be text, not {value!r}")
                return ""
            return value.strip()

        expect = section("expect", ("glycam_name", "folder_hash"))
        expect_hash = expect.get("folder_hash")
        if expect_hash is not None and not (isinstance(expect_hash, str) and re.fullmatch(r"[0-9a-f]{64}", expect_hash)):
            errors.append("expect.folder_hash must be a SHA-256 (the hash of the folder in the manifest)")
            expect_hash = None
        names = section("names", ("glycam_name", "keep_old_name_as_alias") + NAME_KEYS)
        glycam_name = None
        if names.get("glycam_name") is not None:
            glycam_name = _check_glycam_name(names["glycam_name"], "names.glycam_name", errors) or None
        keep_alias = names.get("keep_old_name_as_alias", True)
        if not isinstance(keep_alias, bool):
            errors.append("names.keep_old_name_as_alias must be true or false")
            keep_alias = True
        overrides = {key: text(names[key], f"names.{key}") for key in NAME_KEYS if key in names}
        for key in ("alpha_glycam", "beta_glycam"):
            if overrides.get(key):
                _check_glycam_name(overrides[key], f"names.{key}", errors)
        glytoucan = section("glytoucan", tuple(GLYTOUCAN_KEYS))
        accessions = {}
        for variant, value in glytoucan.items():
            value = text(value, f"glytoucan.{variant}")
            if value and not _GLYTOUCAN_ID.match(value):
                errors.append(f"glytoucan.{variant} is not a GlyTouCan accession: {value!r}")
            accessions[variant] = value
        curated = section("curated", _CURATED_KEYS)
        checked_curated: Dict[str, Any] = {}
        for key, value in curated.items():
            if key == "description":
                checked_curated[key] = text(value, "curated.description")
            elif not isinstance(value, list) or not all(isinstance(item, str) for item in value):
                errors.append(f"curated.{key} must be a list of texts")
            else:
                checked_curated[key] = [item.strip() for item in value if item.strip()]
        keywords = section("keywords", entry_complete.KEYWORD_EDITS)
        if "replace" in keywords and len(keywords) > 1:
            errors.append("keywords is either {add, remove} or {replace}")
        checked_keywords: Dict[str, List[str]] = {}
        for key, value in keywords.items():
            if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
                errors.append(f"keywords.{key} must be a list of texts")
            else:
                checked_keywords[key] = [item.strip() for item in value if item.strip()]
        simulation = record.get("simulation", {}) or {}
        if not isinstance(simulation, dict):
            errors.append("simulation must be an object")
            simulation = {}
        try:                                    # the rules of the submission record: units in the names
            entry_complete.Submission.parse({"glycoshape_id": glycoshape_id or "GS00000", "glycam_name": "x",
                                             "simulation": simulation})
        except SubmissionError as exc:
            errors.append(str(exc).replace("the submission record cannot be used: ", ""))
        public_note = record.get("public_note")
        if public_note is not None:
            public_note = text(public_note, "public_note")
        if errors:
            raise SubmissionError("the changes record cannot be used: " + "; ".join(errors))
        return cls(
            glycoshape_id=glycoshape_id,
            expect_glycam_name=expect.get("glycam_name") if isinstance(expect.get("glycam_name"), str) else None,
            expect_folder_hash=expect_hash,
            glycam_name=glycam_name,
            keep_old_name_as_alias=keep_alias,
            names=overrides,
            glytoucan=accessions,
            curated=checked_curated,
            keywords=checked_keywords,
            simulation=dict(simulation),
            curator_note=text(record.get("curator_note"), "curator_note"),
            public_note=public_note,
            author=text(record.get("author"), "author"),
        )

    def record(self) -> Dict[str, Any]:
        """The normal form, as it is kept in the history."""
        names: Dict[str, Any] = dict(self.names)
        if self.glycam_name is not None:
            names["glycam_name"] = self.glycam_name
            names["keep_old_name_as_alias"] = self.keep_old_name_as_alias
        return {
            "schema": CHANGES_SCHEMA, "schema_version": CHANGES_SCHEMA_VERSION,
            "glycoshape_id": self.glycoshape_id,
            "expect": {"glycam_name": self.expect_glycam_name, "folder_hash": self.expect_folder_hash},
            "names": names, "glytoucan": dict(self.glytoucan), "curated": dict(self.curated),
            "keywords": dict(self.keywords), "simulation": dict(self.simulation),
            "curator_note": self.curator_note, "public_note": self.public_note, "author": self.author,
        }


