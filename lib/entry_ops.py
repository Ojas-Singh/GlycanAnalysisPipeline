@dataclass
class Published:
    """What is stored about one published entry, as far as an operation needs it."""

    glycan_id: str
    data: Dict[str, Any]                 # its row of GLYCOSHAPE.json (= data.json)
    published_name: str                  # archetype.name: the name the entry is published under
    raw_name: str                        # the GLYCAM name of its raw entry (differs for entries named by an accession)
    folder_hash: str
    files: Dict[str, Dict[str, Any]]     # its files in the stored manifest
    record: Optional[Dict[str, Any]]     # the record of its last publication, when there is one
    raw_index: Optional[Dict[str, Any]]


def read_published(target: Target, store: Store, raw_store: Store, database: entry_publish.Database,
                   glycan_id: str) -> Published:
    """The published entry ``glycan_id``; raises :class:`Refused` when it is not published."""
    if glycan_id not in database.inventory or glycan_id not in database.manifest["glycans"]:
        tombstone = database.withdrawn.get(glycan_id)
        raise Refused(f"{glycan_id} is not published" + (" (it was withdrawn)" if tombstone else ""))
    raw_index_bytes = raw_store.read_optional(f"{target.raw_prefix}/{archive.INDEX_FILE}")
    try:
        raw_index = None if raw_index_bytes is None else json.loads(raw_index_bytes)
    except ValueError:
        raw_index = None
    data = database.inventory[glycan_id]
    published_name = id_registry.full_glycam_name(data) or ""
    raw_name = entry_publish._published_names(database, raw_index).get(glycan_id, published_name)
    record_bytes = store.read_optional(target.record_key(glycan_id))
    try:
        record = None if record_bytes is None else json.loads(record_bytes)
    except ValueError:
        record = None
    if record is not None and record.get("glycoshape_id") != glycan_id:
        record = None
    entry = database.manifest["glycans"][glycan_id]
    return Published(glycan_id, data, published_name, raw_name, entry["hash"], entry["files"], record, raw_index)


def check_new_name(database: entry_publish.Database, published: Published, new_name: str) -> List[str]:
    """Why ``new_name`` cannot be the name of the entry: published or withdrawn under another ID."""
    refused: List[str] = []
    names = entry_publish._published_names(database, published.raw_index)
    for other, name in sorted(names.items()):
        if other == published.glycan_id:
            continue
        inventory_name = id_registry.full_glycam_name(database.inventory.get(other) or {})
        if new_name in (name, inventory_name):
            refused.append(f"the name is published as {other}: a rename may not take the name of another entry")
    for other, item in sorted(database.withdrawn.items()):
        if other != published.glycan_id and item.get("glycam_name") == new_name:
            refused.append(f"the name was published as {other} and withdrawn: its ID stays with it")
    return refused


