def heavy_atoms(topology_pdb: Path, cap: int = 300) -> int:
    """Atoms of the PCA landscape: heavy atoms outside the reducing ``ROH``, at most ``cap``."""
    count = 0
    with open(topology_pdb, "r", encoding="utf-8", errors="replace") as handle:
        for line in handle:
            if not line.startswith(("ATOM  ", "HETATM")):
                continue
            if line[17:21].strip() == "ROH":
                continue
            element = line[76:78].strip() or line[12:16].strip().lstrip("0123456789")[:1]
            if element.upper().startswith("H"):
                continue
            count += 1
    return min(count, cap)


def memory_estimate_gb(frames: int, atoms: int, workers: int) -> float:
    """Peak memory of the analysis of one entry, in GB (conservative).

    One matrix of 8 bytes x retained frames x atom pairs of the landscape
    dominates (README, "One entry on a compute node"); measured peaks were
    19.0 to 19.4 GiB for 160,016 frames of 172 such atoms (8 and 16 workers)
    and 1.9 to 3.0 GiB for 50,005 frames of 62.
    """
    pairs = atoms * (atoms - 1) // 2
    return round(8.0 * frames * pairs / 1e9 * 1.05 + 1.5 + 0.1 * workers, 2)


def run_analysis(entry_dir: Path, result_dir: Path, workers: int, exclude: List[str], log_path: Path,
                 levels: Optional[Tuple[int, ...]] = None) -> Dict[str, Any]:
    """``scripts/run_entry.py`` in a process of its own; returns its result.  Raises on failure.

    A process of its own: a run that is killed (out of memory) leaves the
    calling service standing, and the settings of the run do not leak.
    """
    command = [sys.executable, str(REPO_ROOT / "scripts" / "run_entry.py"), str(entry_dir), str(result_dir),
               "--workers", str(workers)]
    if levels:
        command += ["--levels", ",".join(str(level) for level in levels)]
    for name in exclude:
        command += ["--exclude-replica", name]
    environment = dict(os.environ, MPLBACKEND="Agg", PYTHONUNBUFFERED="1")
    log_path.parent.mkdir(parents=True, exist_ok=True)
    with open(log_path, "wb") as handle:
        completed = subprocess.run(command, stdout=handle, stderr=subprocess.STDOUT, env=environment, check=False)
    tail = log_path.read_text(encoding="utf-8", errors="replace")[-2000:]
    if completed.returncode == 2:
        raise Refused(f"the raw entry cannot be analysed: {tail.strip().splitlines()[-1] if tail.strip() else ''}")
    if completed.returncode < 0:
        raise OperationError(f"the analysis was killed by signal {-completed.returncode} (out of memory?); "
                             f"see {log_path}")
    if completed.returncode != 0:
        raise OperationError(f"the analysis failed (exit status {completed.returncode}); see {log_path}: "
                             + " ".join(tail.strip().splitlines()[-2:]))
    return json.loads((result_dir / "result.json").read_text(encoding="utf-8"))


def _bundle_source(published: Published, submission: Dict[str, Any], operation: Dict[str, Any]) -> Dict[str, Any]:
    simulation = submission.get("simulation") or {}
    length = simulation.get("simulation_length_ns")
    if length is None and simulation.get("simulation_length_us") is not None:
        length = float(simulation["simulation_length_us"]) * 1000.0
    return {
        "name": published.raw_name[:4000], "simulation_length_ns": length, "time_per_frame_ps": None,
        "md_package": simulation.get("md_package") or None, "force_field": simulation.get("force_field") or None,
        "temperature_k": simulation.get("temperature_k"), "pressure_bar": simulation.get("pressure_bar"),
        "salt_concentration_mm": simulation.get("salt_concentration_mm"),
        "comments": simulation.get("comments") or None, "glytoucan_id": submission.get("glytoucan_id") or None,
        "run_id": f"reanalyse-{published.glycan_id}", "reanalysis": operation,
    }


def reanalyse(
    glycan_id: str,
    target: Target,
    work_dir,
    exclude: Iterable[str] = (),
    simulated: Optional[str] = None,
    note: str = "",
    author: str = "",
    submission_record: Optional[Dict[str, Any]] = None,
    workers: int = 8,
    memory_limit_gb: Optional[float] = None,
    policy: Optional[Policy] = None,
    dry_run: bool = False,
    offline: Optional[bool] = None,
    lookup_timeout: Optional[float] = None,
    lookup_budget: Optional[float] = 300.0,
    refresh: bool = False,
    expect_hash: Optional[str] = None,
    lock_ttl: float = entry_publish.DEFAULT_LOCK_TTL,
    break_lock: bool = False,
    cache_dir=None,
    owner: Optional[str] = None,
    log: Log = print,
    checkpoint: Callable[[str], None] = _noop,
) -> Dict[str, Any]:
    """Analyse the stored raw entry of a published glycan again and publish it in place (same ID).

    ``exclude`` names replicas to leave out (segment names, or the replica
    names of ``replicas.json``); the raw entry keeps them.  ``simulated``
    (``alpha``, ``beta`` or ``auto`` for what the residue code of the
    topology says) declares the anomer that was simulated: when it is not
    the anomer of the name, the entry is renamed to it, its raw entry is
    moved (:func:`plan_raw_move`), and the analysis files the simulated
    structure under that anomer.  ``note`` (for example which GAP fix the
    re-analysis picks up) is kept in the history.  The curated metadata
    are those of the stored entry unless ``submission_record`` gives them.
    ``memory_limit_gb`` refuses an entry whose analysis is estimated to
    need more (:func:`memory_estimate_gb`).

    The analysis runs in the work folder (``raw/``, ``result/``, the bundle
    ``bundle.tar`` and its unpacked ``bundle/``); a second run with the same
    work folder reuses a current analysis and the completed folder, so the
    publication after an approved dry run publishes what the dry run showed
    (``expect_hash``).
    """
    from lib import entry_bundle

    policy = policy or Policy()
    owner = owner or entry_publish.new_owner()
    started = time.perf_counter()
    stats = entry_publish.new_stats()
    static_store = Store(target.static, stats, dry_run)
    raw_store = Store(target.raw, stats, dry_run)
    work = Path(work_dir)
    work.mkdir(parents=True, exist_ok=True)
    exclude = [str(name) for name in exclude if str(name).strip()]
    report = _new_report(REANALYSE, glycan_id, dry_run, owner, work, stats)
    journal: Optional[entry_publish.Journal] = None
    try:
        if not id_registry.is_id(glycan_id):
            raise Refused(f"not a GlycoShape ID: {glycan_id!r}")
        if simulated not in (None, "alpha", "beta", "auto"):
            raise Refused(f"the simulated anomer is alpha, beta or auto, not {simulated!r}")
        with _locked(target, static_store, owner, REANALYSE, glycan_id, lock_ttl, break_lock, dry_run,
                     report, log, checkpoint) as lock:
            database = entry_publish.read_database(target, static_store, work, cache_dir)
            published = read_published(target, static_store, raw_store, database, glycan_id)
            refused: List[str] = []

            # The raw entry, as it is stored.
            if raw_store.read_optional(archive_transfer.entry_key_prefix(target.raw_prefix, published.raw_name)
                                       + archive.MANIFEST_FILE) is None:
                raise Refused(f"no raw entry is stored for {published.raw_name[:100]}")
            log(f"downloading the raw entry {published.raw_name[:80]}")
            row = archive_transfer.download_entry(target.raw, target.raw_prefix, published.raw_name, work / "raw")
            stats["downloaded_bytes"] += row.get("bytes", 0)
            entry_dir = work / "raw" / archive.entry_folder_name(published.raw_name)
            manifest = archive.load_manifest(entry_dir)
            stored_manifest_sha256 = file_sha256(entry_dir / archive.MANIFEST_FILE)[1]

            # The anomer: declared against the name and the residue code.
            evidence = simulated_anomer(entry_dir / archive.TOPOLOGY_FILE)
            named = reducing_end_anomer(published.raw_name)
            declared = evidence["anomer"] if simulated == "auto" else simulated
            if simulated == "auto" and declared is None:
                raise Refused(f"the residue code {evidence['residue']!r} of the reducing residue does not say which "
                              "anomer was simulated: declare it (alpha or beta)")
            new_name = published.raw_name
            if declared is not None and named is None:
                raise Refused("the GLYCAM name has no reducing end a<n>-OH or b<n>-OH: no anomer can be declared")
            if declared is not None and declared != named:
                new_name = with_anomer(published.raw_name, declared)
            report.update(glycam_name=new_name, previous_glycam_name=published.published_name)
            report["anomer"] = {"named": named, "declared": declared, "residue_code": evidence,
                                "renamed": new_name != published.raw_name}
            if declared is not None and evidence["anomer"] is not None and evidence["anomer"] != declared:
                report["warnings"].append(
                    f"the residue code {evidence['residue']} of the reducing residue says {evidence['anomer']}, "
                    f"and {declared} is declared")
            if declared is None and evidence["anomer"] is not None and named is not None and evidence["anomer"] != named:
                report["warnings"].append(
                    f"the residue code {evidence['residue']} of the reducing residue says {evidence['anomer']} and the "
                    f"name says {named}: if the {evidence['anomer']} anomer was simulated, declare it")
            journal = entry_publish.Journal(work, REANALYSE, glycan_id, new_name, owner)
            journal.save()
            renamed = new_name != published.published_name
            if new_name != published.raw_name:
                refused += check_new_name(database, published, new_name)

            # Memory.
            excluded_frames = 0
            try:
                from lib import entry_run as _entry_run

                excluded_rows = _entry_run.resolve_exclusions(entry_dir, {"kind": "archive", "frames": manifest["frames"]},
                                                              exclude)
                excluded_frames = sum(row["frames"] for row in excluded_rows)
            except Exception as exc:                        # EntryError: an unknown replica, all excluded
                raise Refused(str(exc)) from exc
            frames = int(manifest["frames"]) - excluded_frames
            atoms = heavy_atoms(entry_dir / archive.TOPOLOGY_FILE)
            estimate = memory_estimate_gb(frames, atoms, workers)
            report["memory"] = {"estimate_gb": estimate, "limit_gb": memory_limit_gb, "frames": frames,
                                "landscape_atoms": atoms, "workers": workers}
            if memory_limit_gb is not None and estimate > memory_limit_gb:
                raise Refused(f"the analysis needs about {estimate:g} GB ({frames} frames, {atoms} landscape atoms) "
                              f"and the limit is {memory_limit_gb:g} GB: run it where there is more memory")

            # The entry to analyse: the stored one, or the stored one under its new name.
            analysed = entry_dir
            if new_name != published.raw_name:
                kept = journal.data.get("renamed_at")
                renamed_at = kept or journal.data["started"]
                journal.data["renamed_at"] = renamed_at
                journal.save()
                analysed = write_renamed_entry(entry_dir, work / "renamed", new_name, renamed_at,
                                               note or f"the {declared} anomer was simulated")
            levels = tuple(policy.levels) if policy.levels is not None else _configured_levels()
            log(f"analysing {new_name[:80]} ({frames} frames{', without ' + ', '.join(exclude) if exclude else ''}; "
                f"about {estimate:g} GB) with {workers} workers")
            analysis_started = time.perf_counter()
            earlier = work / "result" / "result.json"
            earlier_sha256 = file_sha256(earlier)[1] if earlier.is_file() else None
            result = run_analysis(analysed, work / "result", workers, exclude, work / "analysis.log", levels)
            report["analysis"] = {
                "seconds": round(time.perf_counter() - analysis_started, 3),
                "reused": earlier_sha256 is not None and file_sha256(earlier)[1] == earlier_sha256,
                "excluded_replicas": result["settings"].get("excluded_replicas") or [],
                "frame_quality": result.get("frame_quality"), "summary": result.get("analysis"),
                "pipeline": {key: result["pipeline"].get(key) for key in ("commit", "uncommitted_changes", "code_sha256")},
                "peak_rss_gb": result.get("peak_rss_gb"), "warnings": result.get("warnings") or [],
                "note": note,
            }
            report["warnings"] += result.get("warnings") or []

            # The bundle of the new analysis, written and unpacked as a bundle from the cluster is.
            base_submission, curation, notes = published_submission(published.data, published.published_name,
                                                                     published.record)
            report["curated_from"] = notes
            if submission_record is not None:
                base_submission = submission_record
                report["curated_from"] = ["the submission record given with the command"]
            operation_record = {"operation": REANALYSE, "exclude": exclude, "simulated_anomer": declared,
                                "note": note, "raw_manifest_sha256": stored_manifest_sha256}
            bundle_tar, bundle_dir = work / "bundle.tar", work / "bundle"
            fingerprint = json.dumps([file_sha256(work / "result" / "result.json")[1],
                                      _sha256_bytes((analysed / archive.MANIFEST_FILE).read_bytes())])
            if journal.data.get("bundle_fingerprint") != fingerprint or not (bundle_dir / "bundle.json").is_file():
                for stale in (bundle_tar, bundle_dir):
                    if stale.is_dir():
                        shutil.rmtree(stale)
                    elif stale.exists():
                        stale.unlink()
                entry_bundle.write_bundle(bundle_tar, analysed, work / "result",
                                          _bundle_source(published, base_submission, operation_record),
                                          created=journal.data["started"])
                entry_bundle.open_bundle(bundle_tar, bundle_dir, expected_glycam_name=new_name)
                journal.data["bundle_fingerprint"] = fingerprint
                journal.save()
            bundle = entry_complete.load_bundle(bundle_dir)
            policy_refused, policy_warnings = entry_publish.check_bundle_policy(bundle, policy)
            refused += policy_refused
            report["warnings"] += policy_warnings
            report["bundle"] = {"path": str(bundle_tar), "size": bundle_tar.stat().st_size,
                                "sha256": file_sha256(bundle_tar)[1], **bundle.summary()}

            submission_record_new, curation = apply_changes(
                base_submission, curation, Changes(glycoshape_id=glycan_id), published.published_name, new_name)
            submission_record_new["glycoshape_id"] = glycan_id
            try:
                submission = entry_complete.Submission.parse(submission_record_new)
            except entry_complete.SubmissionError as exc:
                raise Refused(str(exc)) from exc

            def complete() -> Dict[str, Any]:
                folder, data, summary = entry_complete.complete_folder(
                    bundle.static_dir, new_name, bundle.levels, submission, work / "static", offline=offline,
                    lookup_timeout=lookup_timeout, lookup_budget=lookup_budget, names=curation["names"],
                    aliases=curation.get("aliases") or [], keywords=curation.get("keywords") or {},
                    public_note=curation.get("public_note") or "")
                return entry_complete.folder_report(folder, data, bundle.levels, summary, submission,
                                                    list(submission.warnings))

            fingerprint = hashlib.sha256(json.dumps(
                [bundle.sha256, submission.sha256(), curation, list(bundle.levels)], sort_keys=True).encode()).hexdigest()
            entry = _cached_completion(work, journal, fingerprint, refresh, log, complete)
            folder = Path(entry["folder"])
            report["entry"] = _entry_summary(entry)
            report["warnings"] += entry["warnings"]
            if entry["problems"] and not policy.allow_incomplete:
                refused += [f"the entry is not complete: {problem}" for problem in entry["problems"]]
            if expect_hash is not None and expect_hash != entry["hash"]:
                refused.append(f"the folder has the hash {entry['hash'][:16]}... and {expect_hash[:16]}... was approved")
            reps = [f"output/torsion_level_{level}_reps.csv" for level in bundle.levels]
            old_folder = download_folder(target, static_store, database, glycan_id, work / "stored",
                                         only=[name for name in reps if name in published.files])
            new_data = json.loads((folder / "data.json").read_bytes())
            report["diff"] = diff_entry(
                published.data, new_data, published.files, entry["files"],
                {f"level_{level}": old_folder / f"output/torsion_level_{level}_reps.csv" for level in bundle.levels},
                {f"level_{level}": folder / f"output/torsion_level_{level}_reps.csv" for level in bundle.levels})
            report["database"] = {"global_hash": database.global_hash, "glycans": len(database.manifest["glycans"]),
                                  "withdrawn": len(database.withdrawn)}

            if new_name != published.raw_name:
                new_manifest_bytes = (bundle.archive_dir / archive.MANIFEST_FILE).read_bytes()
                plan, move_refused = plan_raw_move(target, raw_store, published.raw_name, new_manifest_bytes,
                                                   bundle.archive_dir, glycan_id, note or f"{declared} anomer simulated")
                refused += move_refused
                raw = {"kind": "move", "plan": plan}
                report["raw"] = describe_raw_move(plan) if plan else None
            else:
                plan, raw_refused = entry_publish.plan_raw(target, raw_store, bundle, policy)
                refused += raw_refused
                if plan and plan["relation"] != "same":
                    refused.append(f"the stored raw entry changed while it was analysed (relation {plan['relation']})")
                raw = {"kind": "bundle", "plan": plan}
                report["raw"] = entry_publish.describe_raw(plan) if plan else None
            report["rename"] = None if not renamed else {
                "from": published.published_name, "to": new_name, "raw": report.get("raw") if raw["kind"] == "move" else
                {"relation": "already-named"}, "old_name_kept_as_alias": True}
            record_extra = {"operation": REANALYSE, "reanalysis": operation_record, "curation": curation,
                            "curator_note": note, "author": author, "raw_manifest_sha256": stored_manifest_sha256}
            report = publish_version(
                REANALYSE, target, work, journal, (static_store, raw_store), database, published, folder,
                {**entry, "glycam_name": new_name, "bundle": bundle.summary(),
                 "submission": submission.record()}, report, refused, raw, record_extra, owner, lock, lock_ttl,
                dry_run, offline, cache_dir, bundle, log, checkpoint)
    except Refused as exc:
        if not report["refused"]:
            entry_publish._refusal(report, exc.report.get("refused") if exc.report and exc.report.get("refused")
                                   else [str(exc)])
        if not dry_run:
            exc.report = report
            raise
    return _finish(report, journal, started, dry_run, stats)
