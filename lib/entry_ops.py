def empty_curation() -> Dict[str, Any]:
    return {"names": {}, "keywords": {}, "public_note": "", "aliases": []}


def _number(value: Any) -> Optional[float]:
    if isinstance(value, bool) or value in (None, ""):
        return None
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    return number if math.isfinite(number) and number >= 0 else None


def published_submission(data: Dict[str, Any], glycam_name: str, record: Optional[Dict[str, Any]] = None
                         ) -> Tuple[Dict[str, Any], Dict[str, Any], List[str]]:
    """The submission record and the curation of a published entry: ``(submission, curation, notes)``.

    When the storage keeps the record of the last publication of the entry
    (``publish-state/.../entries/GSxxxxx.json``, written by this code), its
    submission and curation are the curated metadata.  Otherwise (the
    entries of the bulk publication) they are read back from ``data.json``:
    the simulation fields with their units, the archetype accession as the
    accession to use when the lookups find none, the keyword ``Source:<type>``,
    and as curated what the static stage does not derive: keywords other
    than the class keywords and ``MD:``/``FF:``/``Source:``, common names
    other than the Oxford name and the ganglioside names of the accessions,
    the aliases, and a description that is not the generated one (a
    generated description that ends in a submission comment gives the
    comment).  ``notes`` say what was read how.
    """
    from lib import glyclass
    from lib.glymeta import GlycanMetadataProcessor

    notes: List[str] = []
    archetype = data.get("archetype") if isinstance(data.get("archetype"), dict) else {}
    glycan_id = archetype.get("ID") or ""
    if record and isinstance(record.get("submission"), dict):
        submission = copy.deepcopy(record["submission"])
        submission["glycam_name"] = glycam_name
        curation = {**empty_curation(), **(record.get("curation") or {})}
        notes.append("curated metadata from the record of the last publication")
        return submission, curation, notes

    search = data.get("search_meta") if isinstance(data.get("search_meta"), dict) else {}
    simulation: Dict[str, Any] = {}
    for key, name, unit in (("length", "simulation_length_us", "us"), ("temperature", "temperature_k", "K"),
                            ("pressure", "pressure_bar", "bar"), ("salt", "salt_concentration_mm", "mM")):
        value = archetype.get(key)
        number = _number(value)
        if number is not None and not (key == "temperature" and number == 0):
            simulation[name] = number
        elif value not in (None, ""):
            notes.append(f"archetype.{key} is {value!r}, not a {'temperature' if key == 'temperature' else 'number'}: "
                         "left out")
    for key, name in (("package", "md_package"), ("forcefield", "force_field"), ("water", "water_model")):
        if isinstance(archetype.get(key), str) and archetype[key].strip():
            simulation[name] = archetype[key].strip()
    keywords = [str(item) for item in search.get("keywords") or []]
    sources = [item.split(":", 1)[1] for item in keywords if item.startswith("Source:")]
    if sources:
        simulation["source_type"] = sources[0]
    # The class keywords and MD:/FF:/Source: follow from the names and the simulation fields (an MD: or FF:
    # keyword that no longer matches them is stale, not curated).
    curated_keywords = [item for item in keywords if item not in glyclass.CLASS_KEYWORDS
                        and not item.startswith(("MD:", "FF:", "Source:"))]
    processor = GlycanMetadataProcessor(".", pb_client=None)
    derived_names = {name.casefold() for name in processor.get_common_names(data)}
    common_names = [name for name in search.get("common_names") or [] if str(name).casefold() not in derived_names]
    description = str(search.get("description") or "")
    generated = processor._generate_description(data, {"user_comments": ""})
    comments = ""
    if description == generated:
        description = ""
    elif generated and description.startswith(generated + " "):
        comments = description[len(generated) + 1:].strip()
        description = ""
        notes.append("the description is the generated one with a submission comment: the comment is kept")
    elif description.startswith(f"{glycan_id} is a glycan with IUPAC notation "):
        # generated from older fields (an empty simulation, for example): written again; a comment after the
        # last generated sentence ("Composed of ...") is kept
        at = description.find("Composed of ")
        end = description.find(". ", at) if at >= 0 else -1
        if end >= 0 and description[end + 2:].strip():
            comments = description[end + 2:].strip()
        description = ""
        notes.append("the description was generated from older fields: generated again"
                     + (", its submission comment kept" if comments else ""))
    elif description:
        notes.append("the description is not the generated one: kept as the curated description")
    if comments:
        simulation["comments"] = comments
    submission = {
        "schema": entry_complete.SUBMISSION_SCHEMA, "schema_version": entry_complete.SUBMISSION_SCHEMA_VERSION,
        "glycoshape_id": glycan_id, "glycam_name": glycam_name, "simulation": simulation,
        "glytoucan_id": archetype.get("glytoucan") if _GLYTOUCAN_ID.match(str(archetype.get("glytoucan") or "")) else "",
        "curated": {"common_names": common_names, "aliases": list(search.get("aliases") or []),
                    "description": description, "keywords": curated_keywords},
    }
    curation = empty_curation()
    if search.get("curator_note"):
        curation["public_note"] = str(search["curator_note"])
    notes.append("curated metadata read back from the published data.json (no record of a publication)")
    return submission, curation, notes


def apply_changes(submission: Dict[str, Any], curation: Dict[str, Any], changes: Changes, old_name: str,
                  new_name: str) -> Tuple[Dict[str, Any], Dict[str, Any]]:
    """The submission and curation after the changes."""
    submission = copy.deepcopy(submission)
    curation = {**empty_curation(), **copy.deepcopy(curation)}
    submission["glycam_name"] = new_name
    simulation = dict(submission.get("simulation") or {})
    if "simulation_length_ns" in changes.simulation or "simulation_length_us" in changes.simulation:
        simulation.pop("simulation_length_ns", None)
        simulation.pop("simulation_length_us", None)
    simulation.update(changes.simulation)
    submission["simulation"] = {key: value for key, value in simulation.items() if value not in (None, "")}
    curated = dict(submission.get("curated") or {})
    curated.update(changes.curated)
    submission["curated"] = curated
    names = dict(curation.get("names") or {})
    for key, value in changes.names.items():
        if value:
            names[key] = value
        else:
            names.pop(key, None)
    for variant, value in changes.glytoucan.items():
        key = GLYTOUCAN_KEYS[variant]
        if value:
            names[key] = value
        else:
            names.pop(key, None)
    curation["names"] = names
    if changes.keywords:
        if "replace" in changes.keywords:
            curation["keywords"] = {"replace": list(changes.keywords["replace"])}
        else:
            previous = curation.get("keywords") or {}
            if "replace" in previous:
                base = [k for k in previous["replace"] if k.casefold() not in {r.casefold() for r in changes.keywords.get("remove", [])}]
                curation["keywords"] = {"replace": base + list(changes.keywords.get("add", []))}
            else:
                add = [k for k in previous.get("add", []) if k.casefold() not in {r.casefold() for r in changes.keywords.get("remove", [])}]
                remove = [k for k in previous.get("remove", []) if k.casefold() not in {a.casefold() for a in changes.keywords.get("add", [])}]
                curation["keywords"] = {"add": add + list(changes.keywords.get("add", [])),
                                        "remove": remove + list(changes.keywords.get("remove", []))}
    if changes.public_note is not None:
        curation["public_note"] = changes.public_note
    if new_name != old_name and changes.keep_old_name_as_alias:
        aliases = list(curation.get("aliases") or [])
        if old_name not in aliases:
            aliases.append(old_name)
        curation["aliases"] = aliases
    return submission, curation


